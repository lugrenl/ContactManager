-- Manual schema change for existing PostgreSQL databases.
-- The application uses hibernate.hbm2ddl.auto=validate and does not create tables.
-- Apply as a database owner before starting the application:
--   psql -h <host> -U <user> -d <database> -f Add_revoked_tokens.sql

CREATE TABLE IF NOT EXISTS revoked_tokens (
    token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_revoked_tokens_hash UNIQUE (token_hash)
);

CREATE INDEX IF NOT EXISTS idx_revoked_tokens_expires_at
    ON revoked_tokens (expires_at);
