-- Manual PostgreSQL migration from shared many-to-many contacts to personal
-- contacts with exactly one owner (contacts.user_id).
--
-- The application does NOT run this file. It uses hibernate.hbm2ddl.auto=validate,
-- so apply the migration manually during a maintenance window, before starting
-- the version of the application that expects contacts.user_id.
--
-- Run Diagnose_contacts_migration.sql first and review its output.
-- The preflight checks below stop the migration before destructive changes if:
--   * a contact has no users (orphan contact);
--   * one user would receive two contacts with the same four business fields;
--   * required contact fields are NULL;
--   * the target or backup tables already exist.
--
-- A database backup is still required. The old contacts table is kept as
-- contacts_legacy_backup after a successful migration; drop it manually after
-- acceptance. The old user_contacts table is removed only after verification.
--
-- The original contact_id is retained for the owner with the smallest user_id.
-- Every other linked user receives a copy with a newly generated contact_id.

BEGIN;

DO $$
DECLARE
    v_contact_id_type text;
    v_user_id_type text;
    v_link_count bigint;
    v_orphan_count bigint;
    v_invalid_rows bigint;
    v_duplicate_count bigint;
    v_new_count bigint;
    v_mismatch_count bigint;
BEGIN
    IF to_regclass('contacts') IS NULL THEN
        RAISE EXCEPTION 'Migration aborted: table contacts does not exist';
    END IF;
    IF to_regclass('user_contacts') IS NULL THEN
        RAISE EXCEPTION 'Migration aborted: table user_contacts does not exist';
    END IF;
    IF to_regclass('users') IS NULL THEN
        RAISE EXCEPTION 'Migration aborted: table users does not exist';
    END IF;
    IF to_regclass('contacts_new') IS NOT NULL THEN
        RAISE EXCEPTION 'Migration aborted: contacts_new already exists; inspect and remove it manually';
    END IF;
    IF to_regclass('contacts_legacy_backup') IS NOT NULL THEN
        RAISE EXCEPTION 'Migration aborted: contacts_legacy_backup already exists; inspect it manually';
    END IF;

    SELECT format_type(atttypid, atttypmod)
      INTO v_contact_id_type
      FROM pg_attribute
     WHERE attrelid = 'contacts'::regclass
       AND attname = 'contact_id'
       AND NOT attisdropped;

    SELECT format_type(atttypid, atttypmod)
      INTO v_user_id_type
      FROM pg_attribute
     WHERE attrelid = 'users'::regclass
       AND attname = 'user_id'
       AND NOT attisdropped;

    IF v_contact_id_type IS NULL OR v_user_id_type IS NULL THEN
        RAISE EXCEPTION 'Migration aborted: could not determine contact_id/user_id column types';
    END IF;

    SELECT count(*)
      INTO v_invalid_rows
      FROM contacts
     WHERE name IS NULL OR surname IS NULL;

    IF v_invalid_rows > 0 THEN
        RAISE EXCEPTION 'Migration aborted: % contact row(s) have NULL name or surname', v_invalid_rows;
    END IF;

    SELECT count(*)
      INTO v_orphan_count
      FROM contacts c
     WHERE NOT EXISTS (
         SELECT 1 FROM user_contacts uc WHERE uc.contact_id = c.contact_id
     );

    IF v_orphan_count > 0 THEN
        RAISE EXCEPTION 'Migration aborted: % contact row(s) have no owner. Resolve or archive them manually',
            v_orphan_count;
    END IF;

    SELECT count(*)
      INTO v_invalid_rows
      FROM user_contacts uc
     WHERE NOT EXISTS (SELECT 1 FROM contacts c WHERE c.contact_id = uc.contact_id)
        OR NOT EXISTS (SELECT 1 FROM users u WHERE u.user_id = uc.user_id);

    IF v_invalid_rows > 0 THEN
        RAISE EXCEPTION 'Migration aborted: % user_contacts row(s) reference a missing contact or user',
            v_invalid_rows;
    END IF;

    SELECT count(*)
      INTO v_link_count
      FROM user_contacts;

    SELECT count(*)
      INTO v_duplicate_count
      FROM (
          SELECT uc.user_id,
                 c.name,
                 c.surname,
                 COALESCE(c.email, ''),
                 COALESCE(c.phone_number, '')
            FROM contacts c
            JOIN user_contacts uc ON uc.contact_id = c.contact_id
           GROUP BY uc.user_id, c.name, c.surname,
                    COALESCE(c.email, ''), COALESCE(c.phone_number, '')
          HAVING count(*) > 1
      ) duplicates;

    IF v_duplicate_count > 0 THEN
        RAISE EXCEPTION 'Migration aborted: % duplicate contact group(s) would belong to the same user. Resolve them manually before migrating',
            v_duplicate_count;
    END IF;

    EXECUTE format(
        'CREATE TABLE contacts_new (
             contact_id %s GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
             name VARCHAR(255) NOT NULL,
             surname VARCHAR(255) NOT NULL,
             email VARCHAR(255),
             phone_number VARCHAR(255),
             user_id %s NOT NULL
         )',
        v_contact_id_type,
        v_user_id_type
    );

    -- Keep the original ID for the deterministic first owner (smallest user_id).
    INSERT INTO contacts_new (contact_id, name, surname, email, phone_number, user_id)
    SELECT c.contact_id,
           c.name,
           c.surname,
           c.email,
           c.phone_number,
           owner.user_id
      FROM contacts c
      JOIN (
          SELECT contact_id, MIN(user_id) AS user_id
            FROM user_contacts
           GROUP BY contact_id
      ) owner ON owner.contact_id = c.contact_id;

    IF EXISTS (SELECT 1 FROM contacts_new) THEN
        PERFORM setval(
            pg_get_serial_sequence('contacts_new', 'contact_id'),
            GREATEST((SELECT max(contact_id) FROM contacts_new), 1),
            true
        );
    ELSE
        PERFORM setval(pg_get_serial_sequence('contacts_new', 'contact_id'), 1, false);
    END IF;

    -- Every additional owner receives an independent personal copy with a new ID.
    INSERT INTO contacts_new (name, surname, email, phone_number, user_id)
    SELECT c.name,
           c.surname,
           c.email,
           c.phone_number,
           uc.user_id
      FROM contacts c
      JOIN user_contacts uc ON uc.contact_id = c.contact_id
      JOIN (
          SELECT contact_id, MIN(user_id) AS user_id
            FROM user_contacts
           GROUP BY contact_id
      ) owner ON owner.contact_id = c.contact_id
     WHERE uc.user_id <> owner.user_id
     ORDER BY c.contact_id, uc.user_id;

    SELECT count(*) INTO v_new_count FROM contacts_new;
    IF v_new_count <> v_link_count THEN
        RAISE EXCEPTION 'Migration aborted: transferred % row(s), expected % user-contact link(s)',
            v_new_count, v_link_count;
    END IF;

    SELECT count(*)
      INTO v_mismatch_count
      FROM (
          SELECT user_id, count(*) AS expected_count
            FROM user_contacts
           GROUP BY user_id
      ) expected
      FULL OUTER JOIN (
          SELECT user_id, count(*) AS actual_count
            FROM contacts_new
           GROUP BY user_id
      ) actual USING (user_id)
     WHERE expected.expected_count IS DISTINCT FROM actual.actual_count;

    IF v_mismatch_count > 0 THEN
        RAISE EXCEPTION 'Migration aborted: contact counts differ for % user(s)', v_mismatch_count;
    END IF;

    SELECT count(*)
      INTO v_duplicate_count
      FROM (
          SELECT user_id, name, surname,
                 COALESCE(email, ''), COALESCE(phone_number, '')
            FROM contacts_new
           GROUP BY user_id, name, surname,
                    COALESCE(email, ''), COALESCE(phone_number, '')
          HAVING count(*) > 1
      ) duplicates;

    IF v_duplicate_count > 0 THEN
        RAISE EXCEPTION 'Migration aborted: % duplicate group(s) appeared after copying', v_duplicate_count;
    END IF;

    ALTER TABLE contacts RENAME TO contacts_legacy_backup;
    ALTER TABLE contacts_new RENAME TO contacts;

    ALTER TABLE contacts
        ADD CONSTRAINT fk_contacts_owner
        FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE;

    CREATE INDEX idx_contacts_user_id ON contacts(user_id);
    CREATE INDEX idx_contacts_owner_lookup
        ON contacts(user_id, name, surname, email, phone_number);

    DROP TABLE user_contacts;

    IF EXISTS (SELECT 1 FROM contacts) THEN
        PERFORM setval(
            pg_get_serial_sequence('contacts', 'contact_id'),
            GREATEST((SELECT max(contact_id) FROM contacts), 1),
            true
        );
    ELSE
        PERFORM setval(pg_get_serial_sequence('contacts', 'contact_id'), 1, false);
    END IF;
END
$$;

COMMIT;

